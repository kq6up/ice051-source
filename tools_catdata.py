"""Generate src/catdata.for: BLOCK DATA CATBD, the built-in star catalog
(COMMON /CATLG/, /CATNAM/) that ICE.EXE carries pre-initialised in its
data segment.  The 200 entries are byte-identical to records 2..201 of
STAR1.CAT (verified against the executable image)."""
import struct, sys
import numpy as np

cat = sys.argv[1] if len(sys.argv) > 1 else '/tmp/claude-0/icedata/STAR1.CAT'
out = sys.argv[2] if len(sys.argv) > 2 else 'src/catdata.for'
f = open(cat, 'rb').read()


def dfmt(x):
    s = repr(float(x))
    if 'e' in s:
        m, e = s.split('e'); return m + 'D' + str(int(e))
    return s + 'D0'


def rfmt(x):
    s = repr(np.float32(x)).replace('np.float32(', '').rstrip(')')
    if 'e' in s:
        m, e = s.split('e'); return m + 'E' + str(int(e))
    return s + 'E0'


L = []
w = L.append
w('C=======================================================================')
w('C  CATBD  built-in catalog: the first 200 stars of STAR1.CAT (FK5),')
w('C  loaded at start-up exactly as in ICE.EXE (generated by tools_catdata.py)')
w('C=======================================================================')
w('      BLOCK DATA CATBD')
w("      INCLUDE 'catlg.inc'")
w('      DATA ICAT, IFIRST, NSTAR, ILOW, IHIGH / 1, 1, 200, 1, 200 /')
for i in range(200):
    rec = f[68 * (i + 1):68 * (i + 2)]
    n = [rec[8 * j:8 * j + 8].decode('latin1') for j in range(3)]
    n = [x.replace("'", "''") for x in n]
    d = struct.unpack('<4d3f', rec[24:])
    k = i + 1
    w("      DATA (CNAM(%d,J),J=1,3) / '%s', '%s', '%s' /" % (k, *n))
    w('      DATA CRA(%d), CDEC(%d), CPMRA(%d), CPMDEC(%d) /' % (k, k, k, k))
    w('     &     %s, %s, %s, %s /' % tuple(dfmt(x) for x in d[:4]))
    w('      DATA CPARX(%d), CRV(%d), CMAG(%d) / %s, %s, %s /' % (k, k, k, *(rfmt(x) for x in d[4:])))
w('      END')
open(out, 'w').write('\n'.join(L) + '\n')
